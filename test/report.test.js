test("report endpoint rejects AI output that violates the analysis contract", async () => {
  resetRateLimitsForTests();
  await withEnvironment({
    FMP_API_KEY: "test-fmp-key",
    GROQ_API_KEY: "test-groq-key",
    PRIMARY_MARKET_PROVIDER: "fmp"
  }, async () => {
    const originalFetch = globalThis.fetch;
    globalThis.fetch = async (url) => {
      if (String(url).includes("financialmodelingprep.com")) {
        return Response.json([{ symbol: "CONTRACTTEST", price: 100 }]);
      }
      if (String(url).includes("api.groq.com")) {
        // Parseable JSON, but missing most required keys.
        return Response.json({
          choices: [{ message: { content: JSON.stringify({ headline: "Only a headline" }) } }]
        });
      }
      throw new Error(`Unexpected provider URL: ${url}`);
    };

    try {
      const res = mockResponse();
      await reportHandler({
        method: "POST",
        headers: { "x-forwarded-for": "report-contract" },
        body: { stock: { symbol: "CONTRACTTEST", exchange: "NSE" } }
      }, res);

      assert.equal(res.statusCode, 502);
      assert.match(res.body.error, /invalid analysis data/i);
    } finally {
      globalThis.fetch = originalFetch;
    }
  });
});

test("report endpoint surfaces a Groq rate limit as 429 with Retry-After", async () => {
  resetRateLimitsForTests();
  await withEnvironment({
    FMP_API_KEY: "test-fmp-key",
    GROQ_API_KEY: "test-groq-key",
    PRIMARY_MARKET_PROVIDER: "fmp"
  }, async () => {
    const originalFetch = globalThis.fetch;
    globalThis.fetch = async (url) => {
      if (String(url).includes("financialmodelingprep.com")) {
        return Response.json([{ symbol: "LIMITTEST", price: 100 }]);
      }
      if (String(url).includes("api.groq.com")) {
        return new Response(JSON.stringify({ error: { message: "Rate limit reached" } }), {
          status: 429,
          headers: { "retry-after": "30" }
        });
      }
      throw new Error(`Unexpected provider URL: ${url}`);
    };

    try {
      const res = mockResponse();
      await reportHandler({
        method: "POST",
        headers: { "x-forwarded-for": "report-limit" },
        body: { stock: { symbol: "LIMITTEST", exchange: "NSE" } }
      }, res);

      assert.equal(res.statusCode, 429);
      assert.equal(res.headers["retry-after"], "30");
      assert.equal(res.body.retryAfterSeconds, 30);
    } finally {
      globalThis.fetch = originalFetch;
    }
  });
});

test("a successful report records token usage through the AI abstraction", async () => {
  resetRateLimitsForTests();
  resetUsageForTests();
  await withEnvironment({
    FMP_API_KEY: "test-fmp-key",
    GROQ_API_KEY: "test-groq-key",
    PRIMARY_MARKET_PROVIDER: "fmp"
  }, async () => {
    const originalFetch = globalThis.fetch;
    globalThis.fetch = async (url) => {
      if (String(url).includes("financialmodelingprep.com")) {
        return Response.json([{ symbol: "USAGETEST", price: 100 }]);
      }
      if (String(url).includes("api.groq.com")) {
        return Response.json({
          choices: [{ message: { content: fullAnalysis } }],
          usage: { prompt_tokens: 400, completion_tokens: 120, total_tokens: 520 }
        });
      }
      throw new Error(`Unexpected provider URL: ${url}`);
    };

    try {
      const res = mockResponse();
      await reportHandler({
        method: "POST",
        headers: { "x-forwarded-for": "report-usage" },
        body: { stock: { symbol: "USAGETEST", exchange: "NSE" } }
      }, res);

      assert.equal(res.statusCode, 200);
      assert.equal(res.body.report.headline, "Complete analysis");

      const usage = getUsageSnapshot();
      assert.equal(usage.totals.requests, 1);
      assert.equal(usage.totals.totalTokens, 520);
    } finally {
      globalThis.fetch = originalFetch;
    }
  });
});
