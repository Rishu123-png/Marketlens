const TOOL_NAMES = TOOL_DEFINITIONS.map((tool) => tool.function.name);

export function toolDefinitionsFor(names = TOOL_NAMES) {
  const allowed = new Set(names);
  return TOOL_DEFINITIONS.filter((tool) => allowed.has(tool.function.name));
}

/** Everything a tool may read: built from the envelope, never from a network call. */
export function createToolContext(envelope = {}) {
  return {
    instrument: envelope.instrument ?? null,
    quote: envelope.marketContext?.quote ?? null,
    candles: envelope.marketContext?.recentCandles ?? [],
    candleCount: envelope.marketContext?.candles?.count ?? 0,
    candleSummary: envelope.marketContext?.candles ?? null,
    interval: envelope.marketContext?.candles?.interval ?? null,
    indicators: envelope.technical ?? null,
    evidence: envelope.evidence?.items ?? [],
    evidenceCounts: envelope.evidence?.counts ?? null,
    coverage: envelope.quality?.coverage ?? null,
    quality: envelope.quality ?? null
  };
}

function truncate(text, max = 1_500) {
  const value = typeof text === "string" ? text : JSON.stringify(text);
  return value.length > max ? `${value.slice(0, max - 1)}…` : value;
}

function describeError(error) {
  return {
    ok: false,
    content: JSON.stringify({ error: error.issues?.[0]?.message || "Invalid arguments for this tool." })
  };
}

function runGetQuote(_args, context) {
  if (!context.quote) {
    return {
      ok: true,
      content: JSON.stringify({
        quote: null,
        note: "No verified quote was supplied for this run. Do not estimate or invent a price."
      })
    };
  }
  return {
    ok: true,
    content: JSON.stringify({
      quote: {
        price: context.quote.price,
        change: context.quote.change,
        changePercent: context.quote.changePercent,
        currency: context.quote.currency,
        provider: context.quote.provider,
        providerTimestamp: context.quote.providerTimestamp ?? null,
        freshness: context.quote.freshness ?? null,
        retrievedAt: context.quote.retrievedAt ?? null
      }
    })
  };
}

function runReadCandles(args, context) {
  const parsed = readCandlesSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const available = context.candles;
  if (!available.length) {
    return { ok: true, content: JSON.stringify({ candles: [], note: "No candles were supplied for this run." }) };
  }

  const limit = Math.min(parsed.data.limit ?? 15, available.length);
  return {
    ok: true,
    content: JSON.stringify({
      interval: context.interval,
      totalSupplied: available.length,
      candles: available.slice(-limit)
    })
  };
}

function runGetInstrumentInfo(_args, context) {
  if (!context.instrument) {
    return { ok: true, content: JSON.stringify({ instrument: null, note: "No instrument identity was supplied." }) };
  }
  return { ok: true, content: JSON.stringify({ instrument: context.instrument }) };
}

function readIndicatorValue(name, context) {
  const indicators = context.indicators;
  if (!indicators) {
    return { value: null, note: "No indicator snapshot was calculated for this run." };
  }
  if (!Object.hasOwn(indicators, name)) {
    return {
      value: null,
      note: `Indicator "${name}" is not available.`,
      available: Object.keys(indicators)
    };
  }
  return { value: indicators[name], candles: indicators.candles ?? null };
}

function runReadIndicator(args, context) {
  const parsed = readIndicatorSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const key = parsed.data.name.trim();
  return { ok: true, content: JSON.stringify({ name: key, ...readIndicatorValue(key, context) }) };
}

const DEFAULT_INDICATOR_KEYS = [
  "candles",
  "lastClose",
  "movingAverages",
  "rsi",
  "macd",
  "atr",
  "bollinger",
  "relativeVolume",
  "volumeBaseline"
];

function runGetTechnicalIndicators(args, context) {
  const parsed = getTechnicalIndicatorsSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  if (!context.indicators) {
    return {
      ok: true,
      content: JSON.stringify({
        indicators: {},
        note: "No deterministic indicator snapshot was calculated for this run."
      })
    };
  }

  const keys = parsed.data.names?.length ? parsed.data.names : DEFAULT_INDICATOR_KEYS;
  const values = {};
  const missing = [];
  for (const key of [...new Set(keys)]) {
    if (Object.hasOwn(context.indicators, key)) values[key] = context.indicators[key];
    else missing.push(key);
  }

  return {
    ok: true,
    content: JSON.stringify({
      indicators: values,
      available: Object.keys(context.indicators),
      ...(missing.length ? { missing } : {})
    })
  };
}

function matchEvidence(items, { terms, limit, sourceTypes }) {
  const needle = String(terms ?? "").toLowerCase().trim();
  return items
    .filter((item) => (sourceTypes ? sourceTypes.includes(item.sourceType) : true))
    .filter((item) => {
      if (!needle) return true;
      return `${item.excerpt ?? ""} ${item.publisher ?? ""} ${item.sourceType ?? ""}`
        .toLowerCase()
        .includes(needle);
    })
    .slice(0, limit)
    .map((item) => ({
      evidenceId: item.evidenceId,
      publisher: item.publisher,
      sourceType: item.sourceType,
      publishedAt: item.publishedAt,
      excerpt: truncate(item.excerpt ?? "", 400),
      verification: item.verification,
      duplicateCount: item.duplicateCount ?? 1,
      injectionSignals: item.injectionSignals ?? []
    }));
}

function runSearchEvidence(args, context) {
  const parsed = searchEvidenceSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const matches = matchEvidence(context.evidence, {
    terms: parsed.data.terms,
    limit: parsed.data.limit ?? 5
  });

  return {
    ok: true,
    content: JSON.stringify({
      matches,
      searched: context.evidence.length,
      note: matches.length ? undefined : "No supplied evidence matched those terms; nothing new was fetched."
    })
  };
}

function runGetCompanyNews(args, context) {
  const parsed = getCompanyNewsSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const matches = matchEvidence(context.evidence, {
    terms: parsed.data.terms,
    limit: parsed.data.limit ?? 8,
    sourceTypes: ["news", "filing", "corporate-action", "earnings"]
  });

  return {
    ok: true,
    content: JSON.stringify({
      matches,
      searched: context.evidence.length,
      note: matches.length ? undefined : "No supplied company-news evidence matched; nothing new was fetched."
    })
  };
}

function runGetMarketEvents(args, context) {
  const parsed = getMarketEventsSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const matches = matchEvidence(context.evidence, {
    terms: parsed.data.terms,
    limit: parsed.data.limit ?? 8,
    sourceTypes: ["regulatory", "official", "macro", "filing", "corporate-action"]
  });

  return {
    ok: true,
    content: JSON.stringify({
      matches,
      searched: context.evidence.length,
      note: matches.length ? undefined : "No supplied regulatory or market-event evidence matched; nothing new was fetched."
    })
  };
}

function runGetMarketOverview(_args, context) {
  return {
    ok: true,
    content: JSON.stringify({
      instrument: context.instrument,
      quote: context.quote
        ? {
            price: context.quote.price,
            currency: context.quote.currency,
            provider: context.quote.provider,
            providerTimestamp: context.quote.providerTimestamp ?? null,
            freshness: context.quote.freshness ?? null,
            retrievedAt: context.quote.retrievedAt ?? null
          }
        : null,
      candles: {
        interval: context.interval,
        count: context.candleCount,
        summary: context.candleSummary,
        recentSupplied: context.candles.length
      },
      evidence: context.evidenceCounts,
      coverage: context.coverage,
      dataWarnings: context.quality?.dataWarnings ?? [],
      note: "This describes the data supplied to this run. It is not a forecast and does not prove real-time coverage."
    })
  };
}

function runReadEvidence(args, context) {
  const parsed = readEvidenceSchema.safeParse(args ?? {});
  if (!parsed.success) return describeError(parsed.error);

  const item = context.evidence.find((entry) => entry.evidenceId === parsed.data.evidenceId);
  if (!item) {
    return {
      ok: true,
      content: JSON.stringify({
        found: false,
        note: "That evidenceId is not part of this run. Do not cite it."
      })
    };
  }

  return {
    ok: true,
    content: JSON.stringify({
      found: true,
      evidence: {
        ...item,
        excerpt: truncate(item.excerpt ?? "", 1_200)
      }
    })
  };
}

const IMPLEMENTATIONS = {
  get_quote: runGetQuote,
  get_historical_candles: runReadCandles,
  get_instrument_info: runGetInstrumentInfo,
  get_technical_indicators: runGetTechnicalIndicators,
  get_company_news: runGetCompanyNews,
  get_market_events: runGetMarketEvents,
  get_market_overview: runGetMarketOverview,
  read_candles: runReadCandles,
  read_indicator: runReadIndicator,
  search_evidence: runSearchEvidence,
  read_evidence: runReadEvidence
};

/**
 * Execute one tool call.
 *
 * @param {{name:string, arguments?:string}} call
 * @param {object} context From `createToolContext`.
 * @param {{used?:number}} [budget] Mutated call counter.
 */
export function executeToolCall(call, context, budget = { used: 0 }) {
  const name = String(call?.name ?? "");
  const used = budget.used ?? 0;

  if (used >= MAX_TOOL_CALLS_PER_RUN) {
    return {
      name,
      ok: false,
      content: JSON.stringify({ error: "Tool budget exhausted for this run. Answer with the evidence you already have." })
    };
  }

  budget.used = used + 1;

  const implementation = IMPLEMENTATIONS[name];
  if (!implementation) {
    return {
      name,
      ok: false,
      content: JSON.stringify({ error: `Tool "${name}" is not available.`, available: TOOL_NAMES })
    };
  }

  let args = {};
  try {
    args = typeof call.arguments === "string" ? JSON.parse(call.arguments || "{}") : call.arguments ?? {};
  } catch {
    return { name, ok: false, content: JSON.stringify({ error: "Tool arguments must be valid JSON." }) };
  }

  const outcome = implementation(args, context);
  const content =
    outcome.content.length > MAX_TOOL_OUTPUT_CHARS
      ? outcome.content.slice(0, MAX_TOOL_OUTPUT_CHARS)
      : outcome.content;

  return { name, ok: outcome.ok, content };
}

