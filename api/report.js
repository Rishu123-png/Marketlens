import { getVerifiedQuote } from "./market.js";
import { rateLimit } from "../lib/server/rateLimit.js";
import { analysisReportSchema } from "../shared/schemas/analysis.js";
import { runStructuredCompletion } from "../server/ai/runAgent.js";
import { DEFAULT_MODEL } from "../server/ai/config.js";

function numberOrNull(value) {
  if (
    value === null ||
    value === undefined ||
    value === ""
  ) {
    return null;
  }

  const number = Number(value);

  return Number.isFinite(number)
    ? number
    : null;
}

export default async function handler(
  req,
  res
) {
  if (req.method !== "POST") {
    return res.status(405).json({
      error: "POST required."
    });
  }

  const quota = await rateLimit(req, {
    name: "report",
    limit: 5,
    windowMs: 10 * 60 * 1000
  });
  if (!quota.allowed) {
    res.setHeader?.("Retry-After", String(quota.retryAfterSeconds));
    return res.status(429).json({
      error: "Too many analysis requests. Please try again later.",
      retryAfterSeconds: quota.retryAfterSeconds
    });
  }

  const stock = req.body?.stock;
  const symbol = String(stock?.symbol || "").trim().toUpperCase();
  if (!/^\^?[A-Z0-9._:&-]{1,40}$/.test(symbol)) {
    return res.status(400).json({
      error: "A valid stock symbol is required."
    });
  }

  const apiKey =
    process.env.GROQ_API_KEY;

  if (!apiKey) {
    return res.status(503).json({
      error:
        "Groq AI service is not configured."
    });
  }

  let quote;
  try {
    // Never trust prices or source metadata sent by the browser. Fetch them
    // independently from the configured provider gateway on the server.
    quote = await getVerifiedQuote(symbol, stock.exchange || "");
  } catch (error) {
    return res.status(error.statusCode || 503).json({
      error: "A fresh provider-verified quote is required for AI analysis.",
      details: error.details || []
    });
  }

  const verifiedMetrics = {
    symbol: quote.symbol,
    name: quote.name || symbol,
    exchange: quote.exchange,
    source: quote.source,
    updatedAt: quote.updatedAt,
    price: numberOrNull(quote.price),
    change: numberOrNull(quote.change),
    changePercent: numberOrNull(quote.changePercent),
    open: numberOrNull(quote.open),
    previousClose: numberOrNull(quote.previousClose),
    dayHigh: numberOrNull(quote.dayHigh),
    dayLow: numberOrNull(quote.dayLow),
    volume: numberOrNull(quote.volume)
  };

  if (
    !verifiedMetrics.symbol ||
    verifiedMetrics.price === null
  ) {
    return res.status(400).json({
      error:
        "Groq analysis requires a verified market quote."
    });
  }

  const prompt = `
You are the analysis layer of MarketLens.

Analyze ONLY the verified market metrics supplied below.

VERIFIED DATA:
${JSON.stringify(
  verifiedMetrics,
  null,
  2
)}

STRICT DATA RULES:

1. Treat the VERIFIED DATA block as the only source for current numerical market facts.
2. Never change, replace, or contradict any verified number.
3. Do not invent:
   - another current price
   - market cap
   - P/E ratio
   - revenue
   - profit
   - news
   - earnings results
   - analyst targets
   - dividends
   - technical indicators not calculable from the supplied metrics
4. Do not claim to have browsed the web.
5. If information is missing, clearly say it cannot be determined from the supplied verified data.
6. Do not give BUY, SELL, HOLD, or guaranteed-return advice.
7. Explain what the verified price movement and trading range may indicate in cautious educational language.

Return ONLY valid JSON with exactly these keys:

headline,
summary,
marketRead,
strengths,
risks,
whatToMonitor,
limitations,
dataIntegrity

Required meaning:

headline:
Short neutral headline.

summary:
2 to 4 sentences using the verified metrics accurately.

marketRead:
Explain the current price movement, day range, and available volume data.
If volume or another metric is missing, explicitly say it is unavailable.

strengths:
Array of 3 cautious observations based only on supplied metrics.

risks:
Array of 3 to 5 risk or uncertainty points.
Do not invent company-specific facts.

whatToMonitor:
Array of 4 things the user should verify with real current data before making any decision.

limitations:
State which important analysis cannot be completed from this quote alone.

dataIntegrity:
Must state that the analysis used provider-backed metrics supplied by MarketLens and that no new market price was generated by AI.
`;

  try {
    const completion = await runStructuredCompletion({
      messages: [
        {
          role: "system",
          content: "You are a precise financial-data interpretation assistant. You never fabricate current market information and you never provide personalized investment advice."
        },
        { role: "user", content: prompt }
      ],
      schema: analysisReportSchema,
      config: {
        agent: "legacy-report",
        model: process.env.GROQ_MODEL || DEFAULT_MODEL,
        temperature: 0.1,
        maxOutputTokens: null,
        timeoutMs: 20_000,
        retries: 1,
        backoffMs: 400
      }
    });

    return res.status(200).json({
      report: completion.output,
      analysisSource: "Groq interpretation of verified MarketLens metrics",
      verifiedMetrics
    });
  } catch (error) {
    return sendCompletionError(res, error);
  }
}

/**
 * Map an abstraction-level AI failure onto the HTTP contract this endpoint has
 * always exposed (503 not configured, 429 rate limit, 502 otherwise).
 */
function sendCompletionError(res, error) {
  const cause = error?.cause ?? error;
  const kind = cause?.kind;

  if (kind === "configuration") {
    return res.status(503).json({ error: "Groq AI service is not configured." });
  }
  if (kind === "timeout") {
    return res.status(502).json({ error: "AI analysis provider timed out. Please try again." });
  }
  if (kind === "schema") {
    return res.status(502).json({
      error: "Groq returned invalid analysis data.",
      details: cause?.message
    });
  }
  if (cause?.status === 429) {
    res.setHeader?.("Retry-After", String(cause.retryAfterSeconds ?? 30));
    return res.status(429).json({
      error: "Groq rate limit reached. Please try again shortly.",
      retryAfterSeconds: cause.retryAfterSeconds ?? null
    });
  }
  return res.status(502).json({
    error: "Groq analysis request failed.",
    details: cause?.message || "Unknown AI provider error."
  });
}
